//
//  ClipboardHistoryStoreTests.swift
//  クリップボード履歴の記録条件・重複処理・件数上限・永続化の単体テスト
//
//  ユーザーのクリップボード（NSPasteboard.general）と実ファイルに触れないよう、
//  専用の名前付きペーストボードと一時ディレクトリを注入して検証する。
//

import AppKit
import XCTest
@testable import voicekey

@MainActor
final class ClipboardHistoryStoreTests: XCTestCase {

    private var board: NSPasteboard!
    private var dir: URL!

    override func setUp() async throws {
        board = NSPasteboard(name: .init("voicekey-test-\(UUID().uuidString)"))
        dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("voicekey-clipboard-test-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
    }

    override func tearDown() async throws {
        board.releaseGlobally()
        try? FileManager.default.removeItem(at: dir)
    }

    private func makeStore(limit: Int = 200) -> ClipboardHistoryStore {
        let store = ClipboardHistoryStore(pasteboard: board, directory: dir, limit: limit)
        store.start()
        return store
    }

    /// テスト用ボードにテキストをコピーする（extraTypes は空 Data のマーカーとして付ける）
    private func copy(_ text: String, extraTypes: [String] = []) {
        board.clearContents()
        board.setString(text, forType: .string)
        for type in extraTypes {
            board.setData(Data(), forType: NSPasteboard.PasteboardType(type))
        }
    }

    // 新しいテキストは先頭に記録される
    func testRecordsNewText() {
        let store = makeStore()
        copy("hello")
        store.checkNow()
        copy("world")
        store.checkNow()
        XCTAssertEqual(store.items.map(\.text), ["world", "hello"])
    }

    // 空白だけ・変化なしは記録しない
    func testIgnoresBlankAndUnchanged() {
        let store = makeStore()
        copy("  \n ")
        store.checkNow()
        XCTAssertTrue(store.items.isEmpty)
        copy("a")
        store.checkNow()
        store.checkNow()  // changeCount が同じなら何もしない
        XCTAssertEqual(store.items.count, 1)
    }

    // パスワード管理アプリ（Concealed）・一時データ（Transient）の印付きは記録しない
    func testIgnoresConcealedAndTransient() {
        let store = makeStore()
        copy("secret", extraTypes: ["org.nspasteboard.ConcealedType"])
        store.checkNow()
        copy("temp", extraTypes: [ClipboardHistoryStore.transientType.rawValue])
        store.checkNow()
        copy("auto", extraTypes: ["org.nspasteboard.AutoGeneratedType"])
        store.checkNow()
        copy("1p", extraTypes: ["com.agilebits.onepassword"])
        store.checkNow()
        XCTAssertTrue(store.items.isEmpty)
    }

    // 先頭と同じテキストは何もしない（Paster の書き戻しで繰り上がらない）。途中と同じは先頭へ移す
    func testDuplicateHandling() {
        let store = makeStore()
        copy("a"); store.checkNow()
        copy("b"); store.checkNow()
        let headID = store.items.first?.id
        copy("b"); store.checkNow()
        XCTAssertEqual(store.items.map(\.text), ["b", "a"])
        XCTAssertEqual(store.items.first?.id, headID)

        copy("c"); store.checkNow()
        copy("a"); store.checkNow()
        XCTAssertEqual(store.items.map(\.text), ["a", "c", "b"])
    }

    // limit を超えた分は古い方から捨て、limit を下げたら即座に切り詰めて保存する
    func testLimitTrimming() {
        let store = makeStore(limit: 3)
        for i in 0..<5 {
            copy("t\(i)")
            store.checkNow()
        }
        XCTAssertEqual(store.items.map(\.text), ["t4", "t3", "t2"])

        store.limit = 2
        XCTAssertEqual(store.items.map(\.text), ["t4", "t3"])
        let reloaded = ClipboardHistoryStore(pasteboard: board, directory: dir, limit: 200)
        XCTAssertEqual(reloaded.items.map(\.text), ["t4", "t3"])
    }

    // 別インスタンスで読み直しても残っている（ファイル権限は 0600）
    func testPersistsAcrossInstances() throws {
        let store = makeStore()
        copy("keep me")
        store.checkNow()

        let reloaded = ClipboardHistoryStore(pasteboard: board, directory: dir)
        XCTAssertEqual(reloaded.items.map(\.text), ["keep me"])
        XCTAssertEqual(reloaded.items.first?.id, store.items.first?.id)

        let path = dir.appendingPathComponent("clipboard-history.json").path
        let perms = try FileManager.default.attributesOfItem(atPath: path)[.posixPermissions] as? Int
        XCTAssertEqual(perms, 0o600)
    }

    // stop 中は記録しない（既存の履歴は消さない）。再開してもその間のコピーは拾わない
    func testStopPausesRecording() {
        let store = makeStore()
        copy("before"); store.checkNow()
        store.stop()
        copy("while stopped"); store.checkNow()
        XCTAssertEqual(store.items.map(\.text), ["before"])

        store.start()
        store.checkNow()
        XCTAssertEqual(store.items.map(\.text), ["before"])
        copy("after"); store.checkNow()
        XCTAssertEqual(store.items.map(\.text), ["after", "before"])
    }

    // start 前からある中身は記録しない
    func testIgnoresContentFromBeforeStart() {
        copy("already there")
        let store = makeStore()
        store.checkNow()
        XCTAssertTrue(store.items.isEmpty)
    }

    // clear で全件消え、ファイルにも反映される
    func testClear() {
        let store = makeStore()
        copy("x"); store.checkNow()
        store.clear()
        XCTAssertTrue(store.items.isEmpty)
        XCTAssertTrue(ClipboardHistoryStore(pasteboard: board, directory: dir).items.isEmpty)
    }
}
