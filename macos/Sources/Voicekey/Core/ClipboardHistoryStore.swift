//
//  ClipboardHistoryStore.swift
//  クリップボード履歴の記録と永続化
//
//  Mac 標準のクリップボード履歴が使いにくいので、コピーしたテキストを新しい順に保持し、
//  サイドノッチの履歴パネルから再コピーできるようにする（Maccy のような機能）。
//  NSPasteboard には変更通知が無いため changeCount を 0.5 秒ごとにポーリングする。
//  アプリを再起動しても残るよう Application Support に JSON で保存する（権限 0600）。
//

import AppKit
import Foundation
import os.log

private let log = Logger(subsystem: "com.voicekey.app", category: "clipboard-history")

/// クリップボード履歴 1 件。appBundleID / appName は検出時点の前面アプリ（コピー元の近似）。
struct ClipboardItem: Codable, Identifiable, Equatable {
    let id: UUID
    let text: String
    let date: Date
    let appBundleID: String?
    let appName: String?
}

/// クリップボード履歴のストア。
/// 追加・削除のたびに自動保存される（サイドノッチが @Published を購読して即時反映）。
@MainActor
final class ClipboardHistoryStore: ObservableObject {

    /// 「一時的な書き込みなので履歴に残さないで」の業界標準マーカー（nspasteboard.org）。
    /// voicekey 自身の貼り付け・サイドノッチからのコピーに付け、自分の履歴にも他のクリップボード管理アプリにも残させない
    nonisolated static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")

    /// これを含むコピーは記録しない（パスワード管理アプリ・一時データ・自動生成データ）
    nonisolated static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        transientType,
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    /// 履歴（新しい順）
    @Published private(set) var items: [ClipboardItem] = []

    /// 保持する最大件数。下げたら超過分を古い方から捨てて即保存する
    var limit: Int {
        didSet {
            guard limit != oldValue else { return }
            if trimToLimit() { save() }
        }
    }

    /// 記録中か（stop 中は履歴を消さずに記録だけ止める）。サイドノッチの空状態の文言が見る
    @Published private(set) var isRunning = false

    private let pasteboard: NSPasteboard
    private let fileURL: URL
    /// 最後に見た changeCount（これと違えば中身が変わった）
    private var lastChangeCount: Int
    private var timer: Timer?
    /// 壊れたファイルを退避できなかった（＝元ファイルが残っている）ので保存しない
    private var saveBlocked = false
    /// voicekey 自身（Paster の原本復元・消去）が書いた直後の changeCount。
    /// 復元した原本は印が付かない（ユーザーの元の中身そのもの）ので、これが無いと音声入力のたびに
    /// 原本が「新しいコピー」として履歴へ入る。本文ではなく changeCount で見るのは、
    /// 同じ本文をユーザーが改めてコピーした場合まで捨てないため
    private var selfWrittenChangeCount: Int?
    /// ファイル書き込み専用の直列キュー。貼り付け・復元を担う MainActor を書き込みで待たせず、
    /// 直列にすることで古い内容が新しい内容を後から上書きする順序の逆転も起こさない
    private let saveQueue = DispatchQueue(label: "com.voicekey.clipboard-history.save")

    /// - Parameters:
    ///   - pasteboard: 監視するペーストボード（テストでは専用の名前付きペーストボードを注入する）
    ///   - directory: 保存先ディレクトリ（nil なら ~/Library/Application Support/voicekey）
    ///   - limit: 保持する最大件数
    init(pasteboard: NSPasteboard = .general, directory: URL? = nil, limit: Int = 200) {
        self.pasteboard = pasteboard
        self.limit = limit
        let dir = directory ?? FileManager.default
            .urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("voicekey", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("clipboard-history.json")
        lastChangeCount = pasteboard.changeCount
        let loaded = Self.load(from: fileURL)
        items = Array(loaded.items.prefix(limit))
        saveBlocked = loaded.saveBlocked
    }

    /// 保存済み JSON を読み込む。読めなければ退避して空で開始する（HistoryStore と同じ方針）
    private static func load(from fileURL: URL) -> (items: [ClipboardItem], saveBlocked: Bool) {
        // 空で始めてよいのはファイルが無いときだけ。あるのに読めない（権限・一時的な I/O エラー）ときに
        // 空のまま保存すると中身を上書きして消すので、退避もせず保存だけ止める
        guard FileManager.default.fileExists(atPath: fileURL.path) else { return ([], false) }
        guard let data = try? Data(contentsOf: fileURL) else {
            log.error("クリップボード履歴ファイルを読めないため、上書きしないよう保存を止めます")
            return ([], true)
        }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        if let loaded = try? decoder.decode([ClipboardItem].self, from: data) {
            return (loaded, false)
        }
        // 空で開始したまま保存すると壊れた元ファイルを上書きして消すので退避する。
        // 退避できなければ元ファイルを守るため、このあと保存しない
        let moved = CorruptFileQuarantine.quarantine(fileURL, label: "クリップボード履歴ファイル")
        return ([], moved == nil)
    }

    // MARK: 記録の開始・停止

    /// 記録を始める。起動前（記録 OFF の間）からある中身は記録しないよう、今の changeCount を基準にする
    func start() {
        guard !isRunning else { return }
        isRunning = true
        lastChangeCount = pasteboard.changeCount
        // 録音中のスクロール・メニュー操作中も止まらないよう .common モードで回す
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] timer in
            // ストアが破棄されたらタイマーも止める（テストで作っては捨てるため）
            guard let self else { timer.invalidate(); return }
            MainActor.assumeIsolated { self.checkNow() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// 記録を止める（既存の履歴は消さない）
    func stop() {
        isRunning = false
        timer?.invalidate()
        timer = nil
    }

    /// 全件消去する。ファイルへ書けたときだけ画面上も消す（失敗して画面だけ消えると、再起動で復活して
    /// 消えたと思った履歴が戻ってくる）。結果を確かめるため、ここだけ同期で書き込む
    /// - Returns: 消去できたら true
    @discardableResult
    func clear() -> Bool {
        guard !saveBlocked else { return false }
        do {
            let data = try Self.encode([])
            // 直列キューで書くので、先に積まれた保存が後からこの消去を上書きすることはない
            try saveQueue.sync { try Self.write(data, to: fileURL) }
        } catch {
            log.error("クリップボード履歴の消去に失敗: \(error.localizedDescription)")
            return false
        }
        items = []
        return true
    }

    /// voicekey 自身がペーストボードへ書いた（Paster の原本復元・消去）ことを伝える。
    /// その書き込みでの changeCount の変化は記録しない
    /// - Parameters:
    ///   - pasteboard: 書き込んだペーストボード（監視中のものと違えば無視する）
    ///   - changeCount: 書き込み直後の changeCount
    func noteSelfWrite(on pasteboard: NSPasteboard, changeCount: Int) {
        guard pasteboard.name == self.pasteboard.name else { return }
        selfWrittenChangeCount = changeCount
    }

    // MARK: ポーリング

    /// ペーストボードを 1 回確認し、変わっていれば記録する（タイマーとテストから呼ぶ）
    func checkNow() {
        guard isRunning else { return }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        // 最後の変化が自分の書き込みなら記録しない（復元前の挿入テキストは TransientType で除外済み）
        guard count != selfWrittenChangeCount else { return }

        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0) }) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        // 先頭と同じなら何もしない（Paster が元の中身を書き戻したときに先頭が繰り上がらないように）
        if items.first?.text == text { return }

        let front = NSWorkspace.shared.frontmostApplication
        let item = ClipboardItem(
            id: UUID(), text: text, date: Date(),
            appBundleID: front?.bundleIdentifier, appName: front?.localizedName
        )
        // 途中にある同じテキストは消して先頭へ入れ直す（同じ内容を何行も並べない）
        items.removeAll { $0.text == text }
        items.insert(item, at: 0)
        _ = trimToLimit()
        save()
    }

    // MARK: 保存

    /// limit を超えた分を古い方から捨てる。捨てたら true
    private func trimToLimit() -> Bool {
        let max = Swift.max(limit, 0)
        guard items.count > max else { return false }
        items.removeLast(items.count - max)
        return true
    }

    /// 保存する。エンコードは items を読むので MainActor で行い、ファイル書き込みだけ直列キューへ回す
    private func save() {
        guard !saveBlocked else { return }
        let data: Data
        do {
            data = try Self.encode(items)
        } catch {
            log.error("クリップボード履歴の保存に失敗: \(error.localizedDescription)")
            return
        }
        let fileURL = fileURL
        saveQueue.async {
            do {
                try Self.write(data, to: fileURL)
            } catch {
                // 本文はログに出さない（エラーの種類だけ）
                log.error("クリップボード履歴の保存に失敗: \(error.localizedDescription)")
            }
        }
    }

    /// 積まれている保存が書き終わるまで待つ（テストで別インスタンスから読み直す前に使う）
    func waitForPendingSaves() {
        saveQueue.sync {}
    }

    private nonisolated static func encode(_ items: [ClipboardItem]) throws -> Data {
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        return try encoder.encode(items)
    }

    private nonisolated static func write(_ data: Data, to fileURL: URL) throws {
        try data.write(to: fileURL, options: [.atomic])
        // コピーした文字列にはパスワード以外の秘密も混ざりうるので、本人以外は読めないようにする
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }
}
